#!/usr/bin/env bash
# Bring up Ollama + Open WebUI on this machine's GPU, pull a model sized to fit
# in VRAM, and prove inference is actually running on the GPU.
#
# Idempotent: safe to re-run any time. Re-running re-detects the GPU, rewrites
# .env, and only pulls the model if it isn't already cached.
#
# Overrides (env vars):
#   GPU=nvidia|amd|cpu   skip auto-detection
#   MODEL=<name:tag>     skip VRAM-based model choice (e.g. MODEL=qwen2.5:14b)
#   OLLAMA_PORT=11434  WEBUI_PORT=3000
set -euo pipefail
cd "$(dirname "$0")"

log()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m  %s\n' "$*" >&2; }
die()  { printf '\033[1;31mxx\033[0m  %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "docker not found -- install Docker Engine (Linux) or Docker Desktop (Windows/macOS)."
docker compose version >/dev/null 2>&1 || die "'docker compose' (v2) not available."
docker info >/dev/null 2>&1 || die "Docker daemon not reachable. Is Docker running / are you in the 'docker' group?"

# --- GPU detection -----------------------------------------------------------
vram_mib=0
detect_gpu() {
  if command -v nvidia-smi >/dev/null && nvidia-smi -L >/dev/null 2>&1; then
    echo nvidia; return
  fi
  if [[ -e /dev/kfd ]] && ls /sys/class/drm/card*/device/mem_info_vram_total >/dev/null 2>&1; then
    echo amd; return
  fi
  echo cpu
}
GPU="${GPU:-$(detect_gpu)}"

case "$GPU" in
  nvidia)
    vram_mib=$(nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits | sort -nr | head -1 | tr -d ' ')
    log "NVIDIA GPU: $(nvidia-smi --query-gpu=name --format=csv,noheader | head -1) (${vram_mib} MiB VRAM)"
    # Prove the container runtime can see the GPU before blaming Ollama later.
    if ! docker run --rm --gpus all ubuntu:24.04 true >/dev/null 2>&1; then
      die "Docker can't attach the GPU. Linux: install nvidia-container-toolkit, then 'sudo nvidia-ctk runtime configure --runtime=docker && sudo systemctl restart docker'. Windows: use Docker Desktop's WSL2 backend + current NVIDIA driver."
    fi
    compose_file="docker-compose.yml:gpu.nvidia.yml"
    ;;
  amd)
    bytes=$(cat /sys/class/drm/card*/device/mem_info_vram_total 2>/dev/null | sort -nr | head -1)
    vram_mib=$(( bytes / 1024 / 1024 ))
    log "AMD GPU via ROCm (${vram_mib} MiB VRAM)"
    compose_file="docker-compose.yml:gpu.amd.yml"
    ;;
  cpu)
    warn "No usable GPU detected -- running CPU-only. (Force with GPU=nvidia|amd if detection is wrong.)"
    compose_file="docker-compose.yml"
    ;;
  *) die "GPU must be nvidia, amd, or cpu (got '$GPU')." ;;
esac

# --- Model sizing --------------------------------------------------------------
# Rough rule: Q4 weights ~= 0.6 GB per billion params, plus headroom for KV cache.
pick_model() {
  local v=$1
  if   (( v >= 22000 )); then echo "qwen2.5:32b"
  elif (( v >= 14000 )); then echo "qwen2.5:14b"
  elif (( v >= 10000 )); then echo "gemma3:12b"
  elif (( v >=  7000 )); then echo "llama3.1:8b"
  else                        echo "llama3.2:3b"
  fi
}
MODEL="${MODEL:-$(pick_model "$vram_mib")}"
log "Model: $MODEL"

# --- Write .env (the single source of truth for later `docker compose` calls) --
{
  echo "# Generated by up.sh on $(date -Iseconds) -- re-run up.sh to regenerate."
  echo "COMPOSE_FILE=$compose_file"
  echo "COMPOSE_PATH_SEPARATOR=:"
  echo "GPU=$GPU"
  echo "MODEL=$MODEL"
  echo "OLLAMA_PORT=${OLLAMA_PORT:-11434}"
  echo "WEBUI_PORT=${WEBUI_PORT:-3000}"
  if [[ "$GPU" == amd ]]; then
    echo "VIDEO_GID=$(getent group video | cut -d: -f3 || echo 44)"
    echo "RENDER_GID=$(getent group render | cut -d: -f3 || echo 110)"
  fi
} > .env

# --- Up -----------------------------------------------------------------------
log "Starting containers..."
docker compose up -d --wait ollama
docker compose up -d open-webui

if docker compose exec -T ollama ollama list | awk 'NR>1{print $1}' | grep -qx "$MODEL"; then
  log "$MODEL already cached, skipping pull."
else
  log "Pulling $MODEL (first time only -- this is a few GB)..."
  docker compose exec -T ollama ollama pull "$MODEL"
fi

# --- Smoke test + GPU proof ---------------------------------------------------
./bench.sh "$MODEL"

log "Where is the model loaded? (want '100% GPU')"
docker compose exec -T ollama ollama ps

cat <<EOF

  Chat UI:      http://localhost:${WEBUI_PORT:-3000}
  Ollama API:   http://localhost:${OLLAMA_PORT:-11434}   (OpenAI-compatible at /v1)
  CLI chat:     docker compose exec -it ollama ollama run $MODEL
  Benchmark:    ./bench.sh [model]
  Stop:         docker compose down        (models are kept)
  Nuke all:     docker compose down -v     (deletes downloaded models)
EOF
