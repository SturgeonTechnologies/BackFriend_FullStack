# Windows twin of up.sh: Ollama + Open WebUI on your GPU via Docker Desktop (WSL2 backend).
# Idempotent -- re-run any time.
#   .\up.ps1                      # auto-detect
#   .\up.ps1 -Model qwen2.5:14b   # pick the model yourself
#   .\up.ps1 -Gpu cpu             # force CPU
# AMD on Windows: Docker can't pass AMD GPUs through. Use the native installer
# (https://ollama.com/download) instead -- see README.
[CmdletBinding()]
param(
  [ValidateSet('auto', 'nvidia', 'cpu')] [string]$Gpu = 'auto',
  [string]$Model = '',
  [int]$OllamaPort = 11434,
  [int]$WebuiPort = 3000
)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

function Log($m)  { Write-Host "==> $m" -ForegroundColor Cyan }
function Warn($m) { Write-Host "!!  $m" -ForegroundColor Yellow }
function Die($m)  { Write-Host "xx  $m" -ForegroundColor Red; exit 1 }

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { Die 'docker not found -- install Docker Desktop.' }
docker info *> $null; if ($LASTEXITCODE) { Die 'Docker Desktop is not running.' }

$vramMiB = 0
if ($Gpu -eq 'auto') {
  $Gpu = 'cpu'
  if (Get-Command nvidia-smi -ErrorAction SilentlyContinue) {
    nvidia-smi -L *> $null; if (-not $LASTEXITCODE) { $Gpu = 'nvidia' }
  }
}

if ($Gpu -eq 'nvidia') {
  $vramMiB = (nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits |
              ForEach-Object { [int]$_.Trim() } | Measure-Object -Maximum).Maximum
  $name = (nvidia-smi --query-gpu=name --format=csv,noheader | Select-Object -First 1)
  Log "NVIDIA GPU: $name ($vramMiB MiB VRAM)"
  docker run --rm --gpus all ubuntu:24.04 true *> $null
  if ($LASTEXITCODE) { Die "Docker can't attach the GPU. Settings > General > 'Use the WSL 2 based engine', and update the NVIDIA driver." }
  $composeFile = 'docker-compose.yml:gpu.nvidia.yml'
} else {
  $amd = Get-CimInstance Win32_VideoController | Where-Object { $_.Name -match 'AMD|Radeon' }
  if ($amd) { Warn "AMD GPU found ($($amd[0].Name)) but Docker can't use it on Windows. Install native Ollama instead: https://ollama.com/download" }
  Warn 'Running CPU-only.'
  $composeFile = 'docker-compose.yml'
}

if (-not $Model) {
  $Model = if     ($vramMiB -ge 22000) { 'qwen2.5:32b' }
           elseif ($vramMiB -ge 14000) { 'qwen2.5:14b' }
           elseif ($vramMiB -ge 10000) { 'gemma3:12b' }
           elseif ($vramMiB -ge 7000)  { 'llama3.1:8b' }
           else                        { 'llama3.2:3b' }
}
Log "Model: $Model"

@"
# Generated by up.ps1 on $(Get-Date -Format o) -- re-run up.ps1 to regenerate.
COMPOSE_FILE=$composeFile
COMPOSE_PATH_SEPARATOR=:
GPU=$Gpu
MODEL=$Model
OLLAMA_PORT=$OllamaPort
WEBUI_PORT=$WebuiPort
"@ | Set-Content -Encoding ascii .env

Log 'Starting containers...'
docker compose up -d --wait ollama;  if ($LASTEXITCODE) { Die 'ollama failed to start: docker compose logs ollama' }
docker compose up -d open-webui;     if ($LASTEXITCODE) { Die 'open-webui failed to start' }

$cached = docker compose exec -T ollama ollama list | Select-Object -Skip 1 | ForEach-Object { ($_ -split '\s+')[0] }
if ($cached -contains $Model) { Log "$Model already cached, skipping pull." }
else {
  Log "Pulling $Model (first time only -- a few GB)..."
  docker compose exec -T ollama ollama pull $Model
}

# --- Smoke test / benchmark ---
$prompt = 'Explain idempotency to a junior SRE in three sentences.'
Log "Prompt ($Model): $prompt"
$r = Invoke-RestMethod -Method Post -Uri "http://localhost:$OllamaPort/api/generate" `
       -ContentType 'application/json' `
       -Body (@{ model = $Model; prompt = $prompt; stream = $false } | ConvertTo-Json)
Write-Host "`n$($r.response.Trim())`n"
'  load:     {0,6:N2}s' -f ($r.load_duration / 1e9)
'  generate: {0,4} tok @ {1,7:N1} tok/s   <- the number that matters' -f $r.eval_count, ($r.eval_count / ($r.eval_duration / 1e9))

Log "Where is the model loaded? (want '100% GPU')"
docker compose exec -T ollama ollama ps

@"

  Chat UI:      http://localhost:$WebuiPort
  Ollama API:   http://localhost:$OllamaPort   (OpenAI-compatible at /v1)
  CLI chat:     docker compose exec -it ollama ollama run $Model
  Stop:         docker compose down        (models are kept)
  Nuke all:     docker compose down -v     (deletes downloaded models)
"@
